DEFAULT_GREY = np.array([0.5, 0.5, 0.5])

# Get number of points
num_points = len(scene_pcd.points)

# Assign colors based on mask indices
colors = np.zeros((num_points, 3))  # Default black, will be overridden

for i in range(num_points):
    mask_idx = pred_masks_indices[i]

    if mask_idx == -1:
        colors[i] = DEFAULT_GREY  # Assign grey
    else:
        colors[i] = COLORS_LIST[mask_idx % len(COLORS_LIST)]  # Modulo index

# Assign colors to point cloud
scene_pcd.colors = o3d.utility.Vector3dVector(colors)

# Visualize the colored point cloud
o3d.visualization.draw_geometries([scene_pcd])
